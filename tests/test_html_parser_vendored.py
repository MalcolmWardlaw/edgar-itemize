class _Recorder(_html_parser.HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=False)
        self.events: list[tuple] = []

    def handle_starttag(self, tag, attrs): self.events.append(("start", tag, tuple(attrs)))
    def handle_startendtag(self, tag, attrs): self.events.append(("startend", tag, tuple(attrs)))
    def handle_endtag(self, tag): self.events.append(("end", tag))
    def handle_data(self, data): self.events.append(("data", data))
    def handle_comment(self, data): self.events.append(("comment", data))
    def handle_entityref(self, name): self.events.append(("entityref", name))
    def handle_charref(self, name): self.events.append(("charref", name))
    def handle_decl(self, decl): self.events.append(("decl", decl))
    def handle_pi(self, data): self.events.append(("pi", data))
    def unknown_decl(self, data): self.events.append(("unknown_decl", data))


def _events(payload: str) -> list[tuple]:
    """The event stream under html_to_blocks's feed protocol: feed, resume with feed("") while
    the buffer moves, close."""
    w = _Recorder()
    w.feed(payload)
    prev = None
    while w.rawdata and w.rawdata != prev:
        prev = w.rawdata
        w.feed("")
    w.close()
    return _fold(w.events)


def _fold(events: list[tuple], n: int = 120) -> list[tuple]:
    """A payload longer than n characters is recorded as its length and SHA-256 prefix."""
    out = []
    for e in events:
        if e[0] in ("data", "charref", "comment") and len(e[1]) > n:
            out.append((e[0], f"<{len(e[1])} chars sha256:{hashlib.sha256(e[1].encode('latin-1')).hexdigest()[:16]}>"))
        else:
            out.append(e)
    return out


